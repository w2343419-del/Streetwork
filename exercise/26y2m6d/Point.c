#include <stdio.h>

int main() {
    // 声明一个包含5个元素的整数数组，初始化为 1, 2, 3, 4, 5
    int a[5] = {1, 2, 3, 4, 5};
    
    // 获取数组的地址，然后加1（跳过整个数组）
    // 转换为 int* 指针。ptr 指向数组之后的内存位置
    int *ptr = (int *)(&a + 1);
    
    // *(a + 1) 访问第2个元素（索引1）= 2
    // *(ptr - 1) 将 ptr 向回移动一个整数位置，指向最后一个元素（索引4）= 5
    // 输出: 2, 5
    printf("%d, %d\n", *(a + 1), *(ptr - 1));
    printf("%d, %d\n", (a + 1), (ptr - 1));
    
    return 0;
}