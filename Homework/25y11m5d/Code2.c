/*描述
都听说过“韩信点兵，多多益善”这个成语，韩信才智过人，从不直接清点人数。
只要让士兵 3 人一排，5 人一排，7 人一排的变换队形，查看队尾人数便能清点队伍总人数。
输入
第1行是一个整数 n，表示随后有 n 组数据。
每组数据占一行，包括三种队形的队尾人数a,b,c，用空格隔开。已知队伍总人数不小于 
10，不大于100。

输出
对每组数据，输出相应的队伍总人数，并换行。不存在则输出 Impossible，并换行。

样例1
输入

2
1 2 3
2 3 2
输出

52
23

样例2
输入
3
1 1 2
2 4 6
2 3 6

输出
16
Impossible
83*/
/**
 * @brief 韩信点兵 - 中国剩余定理应用
 * 
 * 算法思路：
 * 1. 枢举10-100之间的所有数字
 * 2. 检查是否同时满足三个条件：
 *    - num % 3 == a
 *    - num % 5 == b
 *    - num % 7 == c
 * 3. 找到则输出，未找到输出Impossible
 * 
 * 注意：根据中国剩余定理，这个问题在给定范围内有唯一解或无解
 * 
 * 时间复杂度：O(n)，n为查询次数
 * 空间复杂度：O(1)
 */

#include <stdio.h>

int main() {
    int n, a, b, c;
    scanf("%d", &n);

    for (int i = 0; i < n; i++) {
        scanf("%d %d %d", &a, &b, &c);
        int found = 0;
        
        // 枢举10-100之间的所有数
        for (int num = 10; num <= 100; num++) {
            if (num % 3 == a && num % 5 == b && num % 7 == c) {
                printf("%d\n", num);
                found = 1;
                break;
            }
        }
        
        if (!found) {
            printf("Impossible\n");
        }
    }
    
    return 0;
}