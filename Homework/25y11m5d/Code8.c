/**
 * @brief 统计七进制表示中某数字的出现次数
 * 
 * 问题描述：
 * 统计m在7进制表示中数字n的出现次数
 * 
 * 算法分析：
 * - 方法：不断对7取模得到最低位，判断是否等于n
 * - 然后除以7去掉最低位，重复直到m=0
 * - 时间复杂度：O(log₇m)
 * - 空间复杂度：O(1)
 * 
 * 进制转换：
 * 十进制转k进制：不断对k取模得到各位数字
 * 例：100₁₀ = 202₇ (100÷7=14余2, 14÷7=2余0, 2÷7=0余2)
 */
#include <stdio.h>

int main() {
    int m, n;  // m为十进制数，n为要统计的数字
    int digit;  // 七进制的当前位
    int count = 0;  // 数字n出现的次数
    
    scanf("%d %d", &m, &n);
    
    // 转换为七进制并统计
    while (m != 0) {
        digit = m % 7;  // 取七进制的最低位
        m = m / 7;  // 去掉最低位
        
        if (digit == n) {
            count++;
        }
    }
    
    printf("%d\n", count);
    return 0;
}