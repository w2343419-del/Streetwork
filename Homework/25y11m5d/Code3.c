/*描述
冰雹猜想的内容是：对任意正整数 n，反复执行：
若 n 为偶数 → n ÷ 2
若 n 为奇数 → 3n + 1
猜想：无论从哪个正整数出发，最终都会得到结果1。

输入一个正整数，请判断经过多少步能得到1，如果超出10步则停止并输出-1。

输入
一个正整数 n（1 ≤ n ≤ 1000000）。

输出
若能于第 1~10 次内得到 1，输出步数；否则输出-1。

样例
输入

3
输出

7
输入

7
输出

-1
*/
/**
 * @brief 冰雹猜想(Collatz猜想)
 * 
 * 算法思路：
 * 1. 偶数 → n/2
 * 2. 奇数 → 3n+1
 * 3. 计数步骤，直到n=1或超过10步
 * 
 * 注意：这是一个著名的数学未解问题
 * 
 * 时间复杂度：O(log n) 平均情况
 * 空间复杂度：O(1)
 */

#include <stdio.h>

int main() {
    int n;
    scanf("%d", &n);
    
    int steps;
    for (steps = 0; steps <= 10; steps++) {
        if (n == 1) {
            printf("%d\n", steps);
            return 0;
        }
        
        if (n % 2 == 0) {
            n = n / 2;
        } else {
            n = 3 * n + 1;
        }
    }
    
    // 超过10步仍未到达1
    printf("-1\n");
    return 0;
}