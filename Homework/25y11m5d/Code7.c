/**
 * @brief 计算阶乘末尾0的个数
 * 
 * 问题描述：
 * 求m!末尾有多少个0（不需要实际计算m!）
 * 
 * 算法分析：
 * - 末尾0由因子2×5产生
 * - 因子2的数量总是多于因子5
 * - 因此只需统计因子5的个数
 * - 统计方法：⌊m/5⌋ + ⌊m/25⌋ + ⌊m/125⌋ + ...
 * - 时间复杂度：O(log₅m)
 * - 空间复杂度：O(1)
 * 
 * 数学原理：
 * m!中因子5的个数 = Σ⌊m/5^i⌋ (i=1,2,3...)
 * 例：100! → ⌊100/5⌋+⌊100/25⌋+⌊100/125⌋ = 20+4+0 = 24个0
 */
#include <stdio.h>

int main() {
    int n;  // 测试用例数
    scanf("%d", &n);
    
    for (int i = 0; i < n; i++) {
        int m;  // 阶乘的数
        scanf("%d", &m);
        
        // 计算m!中因子5的个数
        // 每个5的倍数贡献1个5，25的倍数额外贡献1个5，等等
        int count = m / 5 + m / 25 + m / 125 + m / 625 + m / 3125;
        
        printf("%d\n", count);
    }
    
    return 0;
}