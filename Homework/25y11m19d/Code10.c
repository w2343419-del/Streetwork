/**
 * @brief 统计字符串中连续数字的个数
 * 
 * 问题描述：
 * 统计字符串中有多少个数字（连续的数字算一个）
 * 
 * 算法分析：
 * - 遍历字符串，检测数字字符
 * - 遇到数字时计数+1，然后跳过后续连续数字
 * - 时间复杂度：O(n)
 * - 空间复杂度：O(n)
 * 
 * 实现要点：
 * 判断字符是否为数字：'0' <= c <= '9'
 */

#include <stdio.h>
int main() {
    int n;
    scanf("%d", &n);

    for (int i = 0; i < n; i++) {
        char s[1000];
        scanf("%s", s);

        int count = 0;
        int j = 0;
        // 遍历字符串，统计连续数字段的个数
        while (s[j] != '\0') {
            if (s[j] >= '0' && s[j] <= '9') {
                // 遇到数字，计数+1
                count++;
                // 跳过所有连续的数字
                while (s[j] >= '0' && s[j] <= '9') {
                    j++;
                }
            } else {
                // 跳过非数字字符
                j++;
            }
        }
        printf("%d\n", count);
    }
    
    return 0;
}