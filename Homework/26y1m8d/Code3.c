/**
 * 程序功能: 从N个正整数中找出最小的能被3整除的数
 * 
 * 输入格式: 
 *   - 第一个整数N表示后续数据的个数(1 <= N <= 100)
 *   - 后续N个整数为需要处理的数据
 * 
 * 输出格式:
 *   - 如果存在能被3整除的数，输出其中最小的那个
 *   - 如果不存在符合条件的数，输出"Null"
 * 
 * 实现思路:
 *   1. 读入N的值
 *   2. 循环读入N个数，对每个数进行判断
 *   3. 如果该数能被3整除(num % 3 == 0)，则与当前最小值比较
 *   4. 更新最小值(初始值设为-1表示未找到)
 *   5. 循环结束后，根据最小值是否被更新来输出结果
 * 
 * 时间复杂度: O(N)
 * 空间复杂度: O(1)
 */

#include <stdio.h>
int main() {
    // 步骤1: 读入N值
    int n;
    scanf("%d", &n);
    
    // 步骤2: 初始化最小值为-1（表示未找到）
    int min = -1;
    
    // 步骤3: 循环读入N个数
    for (int i = 0; i < n; i++) {
        int num;
        scanf("%d", &num);
        
        // 步骤4: 判断是否能被3整除
        if (num % 3 == 0) {
            // 更新最小值
            if (min == -1 || num < min) {
                min = num;
            }
        }
    }

    // 步骤5: 输出结果
    if (min != -1) {
        printf("%d\n", min);
    } else {
        printf("Null\n");
    }
    
    return 0;
}
