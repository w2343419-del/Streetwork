/*输入 4 个十进制整数，计算它们的平方和并输出。

输入 4 个十进制整数，范围是−10000~10000。

输出
输出它们的平方和。

样例
输入
1 2 3 4

输出
30*/

/**
 * @brief 计算4个整数的平方和
 * 
 * 算法：直接计算 a² + b² + c² + d²
 * 
 * 时间复杂度：O(1)
 * 空间复杂度：O(1)
 */

#include <stdio.h>

int main() {
    int a, b, c, d;
    scanf("%d %d %d %d", &a, &b, &c, &d);
    
    // 直接计算平方和，避免不必要的中间变量
    printf("%d\n", a * a + b * b + c * c + d * d);
    
    return 0;
}