/*给定0-9数字各若干个，以任意顺序排列这些数字，使得最后得到的数尽可能小（0 不能做首位）。

输入
在一行中给出 10 个非负整数，顺序表示数字 0、数字 1、……数字 9 的个数。
整数间用一个空格分隔。10 个数字的总个数不超过 50，且至少拥有 1 个非 0 的数字。

输出
在一行中输出能够组成的最小的数。

样例
输入
2 2 0 0 0 3 0 0 1 0

输出
10015558*/

/**
 * @brief 用给定的数字组成最小的数
 * 
 * 算法思路：
 * 1. 首位不能是0，所以先输出最小的非0数字（1-9中第一个有的）
 * 2. 剩余的数字按从小到大（0-9）顺序输出
 * 
 * 贪心策略：
 * - 首位选择最小的非零数字
 * - 后续位置按升序排列所有剩余数字
 * 
 * 时间复杂度：O(n)，n为数字总个数
 * 空间复杂度：O(1)
 */

#include <stdio.h>

int main() {
    int counts[10];
    
    // 读取0-9每个数字的个数
    for (int i = 0; i < 10; i++) {
        scanf("%d", &counts[i]);
    }

    // 第一步：输出最小的非0数字作为首位
    for (int i = 1; i < 10; i++) {
        if (counts[i] > 0) {
            printf("%d", i);
            counts[i]--;  // 使用掉一个
            break;
        }
    }

    // 第二步：按升序输出剩余所有数字（包括0）
    for (int i = 0; i < 10; i++) {
        for (int j = 0; j < counts[i]; j++) {
            printf("%d", i);
        }
    }
    
    printf("\n");
    return 0;
}
