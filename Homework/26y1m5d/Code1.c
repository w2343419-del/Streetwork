/**
 * @brief 将正整数表示为2的幂次方之和
 * 
 * 算法思路：
 * 从高位到低位，检查每一位是否为1（即是否能被2^i整除）
 * 由于100000 < 2^17 = 131072，所以最多检查到2^16
 * 
 * 时间复杂度：O(log n)
 * 空间复杂度：O(1)
 */

#include <stdio.h>
#include <math.h>

int main() {
    int n;
    scanf("%d", &n);
    printf("%d=", n);
    
    int power;
    int x;
    
    // 从高位到低位遍历（2^16 = 65536 > 100000，所以从16开始足够）
    for (int x = 16; x >= 0; x--) {
        power = pow(2, x);  // 计算2^x
        if (n >= power) {   // 如果n大于等于当前幂
            n -= power;     // 减去这个幂
            printf("2^%d", x);
            if (n != 0) {   // 如果还有剩余，添加加号
                printf("+");
            }
        }
    }
    printf("\n");
    return 0;
}