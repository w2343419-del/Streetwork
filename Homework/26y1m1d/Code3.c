/*输入一个数组，计算给定下标区间 [L,R] 内的奇数和 S。
数组的下标 L,R 从 0 开始计。

例如：数组为 11,33,21,15,26,78,98,23,37,22，
L=3， R=7，则 S=15+23=38。

输入
输入 1 个正整数 N，表示数组的大小，范围是 1∼100。
然后输入 N 个整数，空格隔开，表示数组的内容，范围是 0∼100000。
最后输入 2 个整数 L 和 R，表示计算区间，满足 0≤L,R<N。

输出
输出奇数和 S。

样例
输入
10
11 33 21 15 26 78 98 23 37 22
3 7

输出
38*/

/**
 * @brief 计算数组指定区间内的奇数和
 * 
 * 算法思路：
 * 1. 读取数组
 * 2. 遍历区间[L, R]
 * 3. 累加所有奇数（通过 num % 2 != 0 判断）
 * 
 * 注意：负数的奇偶性判断
 * - 对于负奇数：-3 % 2 = -1（在C语言中）
 * - 所以应该用 num % 2 != 0 而不是 num % 2 == 1
 * 
 * 时间复杂度：O(n)
 * 空间复杂度：O(n)
 */

#include <stdio.h>

#define MAX_SIZE 100  // 数组最大长度

int main() {
    int n;
    scanf("%d", &n);

    // 读取数组元素
    int arr[MAX_SIZE];
    for (int i = 0; i < n; i++) {
        scanf("%d", &arr[i]);
    }

    // 读取查询区间
    int left, right;
    scanf("%d %d", &left, &right);

    // 计算区间内奇数和
    int sum = 0;
    for (int i = left; i <= right; i++) {
        // 判断是否为奇数（包括负奇数）
        if (arr[i] % 2 != 0) {
            sum += arr[i];
        }
    }

    printf("%d\n", sum);
    return 0;
}
