/**
 * @brief 正整数交替符号求和
 * 
 * 问题描述：
 * 给定正整数n，将各位数字按交替符号(+、-、+、-...)相加求和
 * 最高位(最左边)为正号，之后每位符号交替
 * 
 * 算法分析：
 * 1. 使用字符串读取数字，避免整数溢出
 * 2. 遍历字符串，根据位置索引i的奇偶性决定符号
 *    - i为偶数(0,2,4...)：正号
 *    - i为奇数(1,3,5...)：负号
 * 3. 累加求和
 * 
 * 示例：n=12345 → 1-2+3-4+5 = 3
 * 
 * 时间复杂度：O(d) - d为数字位数，最多9位
 * 空间复杂度：O(d) - 存储数字字符串
 * 
 * 优化点：
 * - 使用字符串处理，支持大整数(最大10^9)
 * - 单次遍历完成计算
 */
/*给定一个正整数 n。n 中的每一位数字会按照下述规则分配一个符号：

最高有效位（最左边）上的数字分配到正号 (+)。
剩余每位上的数字的符号都与其相邻数字相反。
返回所有数字及其对应符号的和。

例如：n=12345， 那么和s=1−2+3−4+5=3

输入
一行，一个正整数 n(1≤n≤10 ^9)。

输出
一个整数，表示所有数字及其对应符号的和。

样例
输入

521
输出

4
输入

886996
输出

0*/
#include <stdio.h>
#include <string.h>
int main() {
    char s[1000];
    scanf("%s", s);
    
    int sum = 0;
    int len = strlen(s);
    for (int i = 0; i < strlen(s); i++) {
        int digit = s[i] - '0';
        
        if (i % 2 == 0) {
            sum += digit;
        } else {
            sum -= digit;
        }
    }
    
    printf("%d", sum);

    return 0;
}
