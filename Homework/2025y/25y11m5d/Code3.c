/**
 * @brief 冰雹猜想（Collatz猜想）验证
 * 
 * 问题描述：
 * 对任意正整数n，反复执行：偶数则除以2，奇数则乘3加1
 * 猜想：最终都会得到1
 * 
 * 算法分析：
 * - 模拟冰雹猜想的迭代过程
 * - 限制最多10步，超过则认为失败
 * - 时间复杂度：O(步数)，最多10步
 * - 空间复杂度：O(1)
 * 
 * 数学背景：
 * 这是数学中著名的未解难题之一
 * 虽然已验证大量数字都满足，但尚未证明对所有正整数成立
 */
#include <stdio.h>

int main() {
    int n;  // 起始数字
    int steps;  // 步数计数
    
    scanf("%d", &n);
    
    // 最多执行10步
    for (steps = 0; steps <= 10; steps++) {
        // 已经达到1，输出步数
        if (n == 1) {
            printf("%d\n", steps);
            return 0;
        }
        
        // 冰雹猜想迭代：偶数/2，奇数×3+1
        if (n % 2 == 0) {
            n = n / 2;
        } else {
            n = 3 * n + 1;
        }
    }
    
    // 超过10步仍未达到1
    printf("-1\n");
    return 0;
}