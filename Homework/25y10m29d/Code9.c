/**
 * @brief 计算数字根（Digital Root）
 * 
 * 问题描述：
 * 不断将一个数的各位数字相加，直到得到一位数
 * 
 * 算法分析：
 * - 方法：循环求和，直到n<10
 * - 每次循环提取各位数字并求和
 * - 时间复杂度：O(log n)，最多迭代log₁₀n次
 * - 空间复杂度：O(1)
 * 
 * 数学优化：
 * 数字根有数学公式：
 * - 若n = 0，结果为0
 * - 若n % 9 = 0 且 n ≠ 0，结果为9
 * - 否则结果为 n % 9
 * 公式法可O(1)时间求解
 */
#include <stdio.h>

int main() {
    int n;  // 输入的整数
    scanf("%d", &n);
    
    // 循环求和，直到n变成一位数
    while (n >= 10) {
        int sum = 0;  // 各位数字之和
        int temp = n;
        
        // 计算各位数字之和
        while (temp > 0) {
            sum += temp % 10;  // 累加最后一位
            temp /= 10;  // 去掉最后一位
        }
        
        n = sum;  // 用新的和替换n
    }

    printf("%d\n", n);
    return 0;
}