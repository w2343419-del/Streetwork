/*
描述

输入一个偶数n（n> 0），计算1/2+1/4+...+1/n，结果保留4位小数

输入

第1行是一个整数m，表示随后有m组数据。每组数据占一行。

输出

每组输入的结果保留4位小数，并换行。

样例

输入           输出

2

6              0.9167

8             1.0417


*/
/**
 * @brief 计算偶数项的倒数和
 * 
 * 算法思路：
 * 计算 1/2 + 1/4 + 1/6 + ... + 1/n
 * 其中 n 为偶数
 * 
 * 注意：使用浮点数计算，避免整数除法
 * 
 * 时间复杂度：O(m * n)
 * 空间复杂度：O(1)
 */

#include <stdio.h>

int main() {
    int m, n;
    scanf("%d", &m);

    for (int i = 0; i < m; i++) {
        scanf("%d", &n);
        
        double sum = 0.0;
        
        // 累加所有偶数项的倒数
        for (int j = 2; j <= n; j += 2) {
            sum += 1.0 / j;
        }
        
        printf("%.4lf\n", sum);
    }
    
    return 0;
}