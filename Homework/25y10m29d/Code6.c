/**
 * @brief 计算整数各位数字之和
 * 
 * 问题描述：
 * 给定一个32位带符号整数，计算其各位数字之和（忽略符号）
 * 
 * 算法分析：
 * - 使用abs()取绝对值，忽略符号
 * - 循环取模得到最后一位，累加到sum
 * - 整除10去掉最后一位
 * - 时间复杂度：O(log₁₀n)，n为数值大小
 * - 空间复杂度：O(1)
 * 
 * 数学原理：
 * 任何整数n = aₖ×10^k + ... + a₁×10 + a₀
 * 各位数字和 = aₖ + ... + a₁ + a₀
 */
#include <stdio.h>
#include <stdlib.h>

int main() {
    int n;  // 输入的整数
    scanf("%d", &n);
    
    n = abs(n);  // 取绝对值，忽略符号
    int sum = 0;  // 各位数字之和
    
    // 逐位提取并累加
    while (n != 0) {
        sum += n % 10;  // 累加最后一位数字
        n /= 10;  // 去掉最后一位
    }
    
    printf("%d\n", sum);
    return 0;
}