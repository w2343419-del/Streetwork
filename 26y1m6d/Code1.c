/**
 * @brief 图像直方图均衡化处理
 * 
 * 该程序对灰度图像实现直方图均衡化。
 * 读取一个 m×n 的图像矩阵，像素值范围为 [0, 63]，
 * 计算像素强度的累计概率分布，
 * 将每个像素重新映射到均衡化的值以增强图像对比度。
 * 
 * 输入：
 *   - 第一行：m（行数）和 n（列数）
 *   - 接下来 m 行：每行 n 个像素值（0-63），用空格分隔
 * 
 * 输出：
 *   - m 行均衡化后的像素值，用空格分隔
 * 
 * 算法步骤：
 *   1. 统计每个灰度级的频率
 *   2. 计算累计概率分布
 *   3. 将每个灰度级映射到新值：round(累计分布 * 63)
 *   4. 输出转换后的图像
 * 
 * 时间复杂度：O(m*n + 64) = O(m*n)
 * 空间复杂度：O(m*n + 64) = O(m*n)
 */

#include <stdio.h>
#include <math.h>

int main() {
    int m, n;
    scanf("%d %d", &m, &n);

    int image[m][n];
    for (int i = 0; i < m; i++) {
        for (int j = 0; j < n; j++) {
            scanf("%d", &image[i][j]);
        }
    }
    
    int count[64] = {0};
    for (int i = 0; i < m; i++) {
        for (int j = 0; j < n; j++) {
            count[image[i][j]]++;
        }
    }

    int mapping[64];
    int total_pixels = m * n;
    double cumulative = 0.0;
    
    for (int gray = 0; gray < 64; gray++) {
        if (count[gray] > 0) {
            double probability = (double)count[gray] / total_pixels;
            cumulative += probability;
            mapping[gray] = (int)round(cumulative * 63);
        }
    }

    for (int i = 0; i < m; i++) {
        for (int j = 0; j < n; j++) {
            if (j > 0) printf(" ");
            printf("%d", mapping[image[i][j]]);
        }
        printf("\n");
    }
    
    return 0;
}